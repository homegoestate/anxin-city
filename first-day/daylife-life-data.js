export const lifeFor = id => scenes[id] || scenes['shuixian-morning'];
export function livingStops(scene, baseStops) {
  return [...baseStops.map(stop => ({...stop, ...(stop.kind === 'resident' || stop.kind === 'office' ? {labelOffset:116} : {})})),
    {id:scene.id+'-neighbor',district:scene.id,name:lifeFor(scene.id).neighbor,role:lifeFor(scene.id).role,kind:'resident',portrait:'neighbor',labelOffset:116,x:130,y:540}];
}
export function residentPlans(scene) {
  const life = lifeFor(scene.id);
  return [
    // Keep the resident on this frontage: name tags stay clear of the upper
    // discovery markers even on a narrow phone with large text enabled.
    {id:scene.id+'-resident',route:[{x:360,y:440},{x:500,y:440}],lines:life.lines.filter((_,i)=>i%2===0)},
    {id:scene.id+'-neighbor',route:[{x:130,y:540},{x:130,y:440}],lines:life.lines.filter((_,i)=>i%2===1)}
  ];
}
